'use strict';
// File-based persistence for templates, versions, trash, settings and autosave.
// Everything lives under one root (Electron's userData), so data survives app updates.
// Writes are atomic (temp file + rename) and serialized; nothing is deleted silently.

const fs = require('node:fs/promises');
const fssync = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { pathToFileURL } = require('node:url');

const ID = /^[A-Za-z0-9][A-Za-z0-9_-]{0,119}$/;
const MAX_TEMPLATE_BYTES = 15 * 1024 * 1024;
const MAX_VERSIONS = 30;

class StoreError extends Error {
  constructor(code, message, details) { super(message); this.code = code; this.details = details; }
}

function assertId(id) {
  if (typeof id !== 'string' || !ID.test(id)) throw new StoreError('invalid-id', 'Invalid template id.');
  return id;
}

async function exists(file) { try { await fs.access(file); return true; } catch { return false; } }

async function atomicWrite(file, text) {
  const tmp = file + '.' + randomUUID().slice(0, 8) + '.tmp';
  await fs.writeFile(tmp, text, { encoding: 'utf8', flag: 'wx' });
  for (let attempt = 0; ; attempt++) {
    try { await fs.rename(tmp, file); return; }
    catch (error) {
      // Windows: antivirus/indexer may briefly lock the target
      if (attempt < 5 && (error.code === 'EPERM' || error.code === 'EBUSY' || error.code === 'EACCES')) {
        await new Promise((r) => setTimeout(r, 60 * (attempt + 1)));
        continue;
      }
      await fs.unlink(tmp).catch(() => {});
      throw error;
    }
  }
}

async function readJson(file, fallback) {
  try { return JSON.parse(await fs.readFile(file, 'utf8')); }
  catch (error) { if (error.code === 'ENOENT') return fallback; throw error; }
}

class TemplateStore {
  constructor(root, { schemaModulePath } = {}) {
    this.root = root;
    this.dirs = {
      templates: path.join(root, 'templates'),
      history: path.join(root, 'history'),
      trash: path.join(root, 'trash'),
      autosave: path.join(root, 'autosave'),
      backups: path.join(root, 'backups')
    };
    this.settingsFile = path.join(root, 'settings.json');
    this.lockFile = path.join(root, 'session.lock');
    // Packaged builds use the CommonJS bundle generated by `npm run build:main`; dev/tests use the ES module.
    const generated = path.join(__dirname, 'generated', 'schema.cjs');
    this.schemaModulePath = schemaModulePath || (fssync.existsSync(generated) ? generated : path.join(__dirname, '..', 'src', 'engine', 'schema.js'));
    this.queue = Promise.resolve();
    this.schema = null;
    this.previousSessionCrashed = false;
  }

  async init() {
    for (const dir of [this.root, ...Object.values(this.dirs)]) await fs.mkdir(dir, { recursive: true });
    this.schema = this.schemaModulePath.endsWith('.cjs') ? require(this.schemaModulePath) : await import(pathToFileURL(this.schemaModulePath).href);
    this.previousSessionCrashed = await exists(this.lockFile);
    await atomicWrite(this.lockFile, JSON.stringify({ pid: process.pid, startedAt: new Date().toISOString() }));
    return this;
  }

  /** Mark a clean shutdown (no crash recovery offered next start). */
  closeSession() {
    try { fssync.unlinkSync(this.lockFile); } catch { /* already gone */ }
  }

  serial(task) {
    const run = this.queue.then(task, task);
    this.queue = run.catch(() => {});
    return run;
  }

  file(id) { return path.join(this.dirs.templates, assertId(id) + '.json'); }

  validate(candidate) {
    let template;
    try { template = this.schema.sanitizeTemplate(candidate); }
    catch (error) { throw new StoreError('invalid-template', error.message); }
    if (!template) throw new StoreError('invalid-template', 'This is not a valid label template.');
    if (!ID.test(template.id)) template.id = this.schema.newId('tpl');
    const text = JSON.stringify(template, null, 2);
    if (Buffer.byteLength(text) > MAX_TEMPLATE_BYTES) throw new StoreError('too-large', 'The template is larger than 15 MB (usually because of large images).');
    return { template, text };
  }

  async list() {
    const entries = await fs.readdir(this.dirs.templates).catch(() => []);
    const items = [];
    for (const name of entries) {
      if (!name.endsWith('.json')) continue;
      try {
        const template = await readJson(path.join(this.dirs.templates, name), null);
        if (!template) continue;
        items.push(this.summary(template));
      } catch (error) {
        items.push({ id: name.replace(/\.json$/, ''), name: name, damaged: true, error: error.message });
      }
    }
    const settings = await this.getSettings();
    const fav = new Set(settings.favorites || []);
    return items.map((t) => ({ ...t, favorite: fav.has(t.id) })).sort((a, b) => String(b.updatedAt).localeCompare(String(a.updatedAt)));
  }

  summary(t) {
    return { id: t.id, name: t.name, category: t.category, description: t.description, tags: t.tags, width: t.page?.width, height: t.page?.height, objectCount: (t.objects || []).length, revision: t.revision, updatedAt: t.updatedAt, createdAt: t.createdAt };
  }

  async get(id) {
    const raw = await readJson(this.file(id), null);
    if (!raw) throw new StoreError('not-found', 'Template not found. It may have been deleted.');
    const { template } = this.validate(raw);
    return template;
  }

  /**
   * Save a template. options.baseRevision: the revision the editor started from.
   * If the stored revision differs, the save is refused with code 'conflict' unless options.force.
   */
  save(candidate, options = {}) {
    return this.serial(async () => {
      const { template } = this.validate(candidate);
      const file = this.file(template.id);
      const current = await readJson(file, null);
      if (current) {
        const stored = Number(current.revision) || 0;
        if (options.createOnly) throw new StoreError('exists', 'A template with this id already exists.');
        if (options.baseRevision !== undefined && options.baseRevision !== null && Number(options.baseRevision) !== stored && !options.force) {
          throw new StoreError('conflict', 'This template was changed elsewhere (saved revision ' + stored + ', you started from ' + options.baseRevision + ').', { storedRevision: stored, storedUpdatedAt: current.updatedAt });
        }
        await this.keepVersion(current);
        template.revision = stored + 1;
        template.createdAt = current.createdAt || template.createdAt;
      } else {
        template.revision = Math.max(1, Number(template.revision) + 1 || 1);
      }
      template.updatedAt = new Date().toISOString();
      await atomicWrite(file, JSON.stringify(template, null, 2));
      await this.touchRecent(template.id);
      return template;
    });
  }

  async keepVersion(template) {
    const dir = path.join(this.dirs.history, assertId(template.id));
    await fs.mkdir(dir, { recursive: true });
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    await atomicWrite(path.join(dir, String(template.revision || 0).padStart(6, '0') + '_' + stamp + '.json'), JSON.stringify(template));
    const versions = (await fs.readdir(dir)).filter((n) => n.endsWith('.json')).sort();
    for (const old of versions.slice(0, Math.max(0, versions.length - MAX_VERSIONS))) await fs.unlink(path.join(dir, old)).catch(() => {});
  }

  async history(id) {
    const dir = path.join(this.dirs.history, assertId(id));
    const names = (await fs.readdir(dir).catch(() => [])).filter((n) => /^\d{6}_[\dT-]+Z?\.json$/.test(n) || n.endsWith('.json')).sort().reverse();
    const out = [];
    for (const name of names) {
      const t = await readJson(path.join(dir, name), null).catch(() => null);
      if (t) out.push({ version: name, revision: t.revision, updatedAt: t.updatedAt, name: t.name, objectCount: (t.objects || []).length });
    }
    return out;
  }

  async getVersion(id, version) {
    if (typeof version !== 'string' || !/^[\w.-]+\.json$/.test(version) || version.includes('..')) throw new StoreError('invalid-version', 'Invalid version.');
    const t = await readJson(path.join(this.dirs.history, assertId(id), version), null);
    if (!t) throw new StoreError('not-found', 'That version no longer exists.');
    return this.validate(t).template;
  }

  /** Create a copy with a new id. */
  async duplicate(id, name) {
    const source = await this.get(id);
    const copy = { ...source, id: this.schema.newId('tpl'), name: String(name || source.name + ' (copy)').slice(0, 120), revision: 0, createdAt: new Date().toISOString() };
    return this.save(copy, { createOnly: true });
  }

  async rename(id, name, baseRevision) {
    const t = await this.get(id);
    return this.save({ ...t, name: String(name || '').trim().slice(0, 120) || t.name }, { baseRevision });
  }

  /** Move to trash (recoverable). */
  remove(id) {
    return this.serial(async () => {
      const file = this.file(id);
      if (!(await exists(file))) throw new StoreError('not-found', 'Template not found.');
      const target = path.join(this.dirs.trash, id + '__' + Date.now() + '.json');
      await fs.rename(file, target);
      const settings = await this.getSettings();
      await this.writeSettings({ ...settings, recent: (settings.recent || []).filter((r) => r !== id), favorites: (settings.favorites || []).filter((f) => f !== id) });
      return { trashed: path.basename(target) };
    });
  }

  async listTrash() {
    const names = (await fs.readdir(this.dirs.trash).catch(() => [])).filter((n) => n.endsWith('.json'));
    const out = [];
    for (const name of names) {
      const t = await readJson(path.join(this.dirs.trash, name), null).catch(() => null);
      const deletedAt = Number(name.split('__')[1]?.replace('.json', '')) || 0;
      out.push({ entry: name, id: t?.id, name: t?.name || name, deletedAt: deletedAt ? new Date(deletedAt).toISOString() : '' });
    }
    return out.sort((a, b) => String(b.deletedAt).localeCompare(String(a.deletedAt)));
  }

  restore(entry) {
    return this.serial(async () => {
      if (typeof entry !== 'string' || !/^[A-Za-z0-9_-]+__\d+\.json$/.test(entry)) throw new StoreError('invalid-entry', 'Invalid trash entry.');
      const raw = await readJson(path.join(this.dirs.trash, entry), null);
      if (!raw) throw new StoreError('not-found', 'That item is no longer in the trash.');
      const { template } = this.validate(raw);
      if (await exists(this.file(template.id))) template.id = this.schema.newId('tpl');
      await atomicWrite(this.file(template.id), JSON.stringify(template, null, 2));
      await fs.unlink(path.join(this.dirs.trash, entry)).catch(() => {});
      return template;
    });
  }

  /** Permanently delete one trash entry (explicit user action only). */
  purge(entry) {
    return this.serial(async () => {
      if (typeof entry !== 'string' || !/^[A-Za-z0-9_-]+__\d+\.json$/.test(entry)) throw new StoreError('invalid-entry', 'Invalid trash entry.');
      await fs.unlink(path.join(this.dirs.trash, entry));
      return true;
    });
  }

  /** Import templates from exported data (single template, array, or bundle). Imported copies get new ids. */
  async importData(data, { keepIds = false } = {}) {
    const list = Array.isArray(data) ? data : Array.isArray(data?.templates) ? data.templates : [data];
    if (list.length > 500) throw new StoreError('too-many', 'An import may contain at most 500 templates.');
    const imported = [];
    const failed = [];
    for (const candidate of list) {
      try {
        const { template } = this.validate(candidate);
        if (!keepIds || await exists(this.file(template.id))) template.id = this.schema.newId('tpl');
        template.revision = 0;
        imported.push(await this.save(template, { createOnly: true }));
      } catch (error) { failed.push({ name: candidate?.name || 'template', error: error.message }); }
    }
    return { imported, failed };
  }

  async exportBundle(ids) {
    const templates = [];
    for (const id of ids) templates.push(await this.get(id));
    return { schema: 'excel-label-studio/bundle', version: 1, exportedAt: new Date().toISOString(), templates };
  }

  // ---------- settings ----------

  async getSettings() {
    const s = await readJson(this.settingsFile, {}).catch(() => ({}));
    return s && typeof s === 'object' && !Array.isArray(s) ? s : {};
  }

  writeSettings(settings) {
    return atomicWrite(this.settingsFile, JSON.stringify(settings, null, 2));
  }

  updateSettings(patch) {
    return this.serial(async () => {
      const next = { ...(await this.getSettings()), ...patch };
      await this.writeSettings(next);
      return next;
    });
  }

  async touchRecent(id) {
    const settings = await this.getSettings();
    const recent = [id, ...(settings.recent || []).filter((r) => r !== id)].slice(0, 15);
    await this.writeSettings({ ...settings, recent });
  }

  setFavorite(id, favorite) {
    assertId(id);
    return this.serial(async () => {
      const settings = await this.getSettings();
      const set = new Set(settings.favorites || []);
      if (favorite) set.add(id); else set.delete(id);
      await this.writeSettings({ ...settings, favorites: [...set] });
      return [...set];
    });
  }

  // ---------- autosave / crash recovery ----------

  async writeAutosave(payload) {
    const text = JSON.stringify({ savedAt: new Date().toISOString(), ...payload });
    if (Buffer.byteLength(text) > MAX_TEMPLATE_BYTES * 2) throw new StoreError('too-large', 'Autosave data is too large.');
    await atomicWrite(path.join(this.dirs.autosave, 'current.json'), text);
  }

  async readRecovery() {
    const data = await readJson(path.join(this.dirs.autosave, 'current.json'), null).catch(() => null);
    if (!data || !data.template) return null;
    try { data.template = this.validate(data.template).template; } catch { return null; }
    return { ...data, crashed: this.previousSessionCrashed };
  }

  async clearAutosave() {
    await fs.unlink(path.join(this.dirs.autosave, 'current.json')).catch(() => {});
  }
}

module.exports = { TemplateStore, StoreError, atomicWrite, ID };
